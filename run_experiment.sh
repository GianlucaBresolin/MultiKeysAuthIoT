#!/usr/bin/env bash
# run_experiment.sh
# Prompt user for the number of keys, generate keys and SKEY,
# write a .env file read by docker-compose and start the compose build.

set -euo pipefail

echo "=== MultiKeyAuthIoT: run_experiment ==="

# Read number of keys (n)
while true; do
  read -r -p "Insert the number of keys to generate (n): " N
  # trim
  N="${N##*( )}"
  N="${N%%*( )}"
  if [[ "$N" =~ ^[0-9]+$ ]] && [ "$N" -gt 0 ] 2>/dev/null; then
    break
  fi
  echo "Invalid value: must be an integer greater than 0."
done

# Generate N base64 keys (32 bytes each)
KEYS_JSON="["
for i in $(seq 1 "$N"); do
  K=$(openssl rand -base64 32)
  KEYS_JSON="$KEYS_JSON\"$K\""
  if [ "$i" -lt "$N" ]; then
    KEYS_JSON="$KEYS_JSON, "
  fi
done
KEYS_JSON="$KEYS_JSON]"

# Generate SKEY (secure key for device)
SKEY=$(openssl rand -base64 32)

# Write project .env so docker-compose and variable substitution can use it
ENVFILE=".env"
cat > "$ENVFILE" <<EOF
# Generated by run_experiment.sh on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
KEYS='${KEYS_JSON}'
SERVER_KEYS='${KEYS_JSON}'
SKEY='${SKEY}'
KEY_COUNT=${N}
EOF

echo "Wrote $ENVFILE with $N keys."

# Export to current shell as well (helps docker compose build arg substitution when invoked)
export KEYS="${KEYS_JSON}"
export SERVER_KEYS="${KEYS_JSON}"
export SKEY="${SKEY}"
export KEY_COUNT="${N}"

# Start docker compose build (will pick up .env in project directory)
docker compose up --build
